#!/usr/bin/env python3
"""Regenerate the language feature catalog from the owned release's exact Rust source.

--source accepts an existing Rust checkout instead of downloading pinned compiler tables.
Library feature availability comes from effective attributes in the loaded source graph.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
RELEASE = ROOT / "crates/ra-jit/src/answers/rustc-1.99.0.json"
OUTPUT = ROOT / "vendor/rust-analyzer/crates/hir/src/channel_features/release.rs"


def generate(source=None):
    release = json.loads(RELEASE.read_text())
    revision = re.search(r"^commit-hash: ([0-9a-f]{40})$", release["verbose"], re.M).group(1)
    text = "// Generated by harness/release_features.py; do not edit.\n"
    text += f"// Rust {release['version']}; commit {revision}.\n"
    def read(relative):
        if source:
            return subprocess.check_output(["git", "-C", str(source), "show", f"{revision}:{relative}"])
        url = f"https://raw.githubusercontent.com/rust-lang/rust/{revision}/{relative}"
        with urllib.request.urlopen(url, timeout=30) as response:
            return response.read()
    for module, status in (("unstable", "ACTIVE"), ("accepted", "ACCEPTED"), ("removed", "REMOVED")):
        relative = f"compiler/rustc_feature/src/{module}.rs"
        data = read(relative)
        if module == "unstable":
            unstable = data.decode()
        names = sorted(re.findall(
            r"^\s*\((?:unstable|internal|incomplete|accepted|removed),\s*([a-zA-Z0-9_]+),",
            data.decode(), re.M))
        if not names or len(names) != len(set(names)):
            raise ValueError(f"invalid feature table: {relative}")
        text += f"// {relative}: sha256 {hashlib.sha256(data).hexdigest()}\n"
        text += f"pub(super) const {status}: &[&str] = &[\n"
        text += "".join(f'    "{name}",\n' for name in names)
        text += "];\n\n"
    pairs = re.search(r"pub const INCOMPATIBLE_FEATURES.*?= &\[(.*?)\];", unstable, re.S).group(1)
    pairs = re.findall(r"\(sym::(\w+), sym::(\w+)\)", pairs)
    text += '#[rustfmt::skip]\npub(super) const INCOMPATIBLE: &[(&str, &str)] = &[\n'
    text += ''.join(f'    ("{a}", "{b}"),\n' for a, b in pairs) + '];\n\n'
    required = re.search(r"pub const DEPENDENT_FEATURES.*?= &\[(.*?)\];", unstable, re.S).group(1)
    required = re.findall(r"\(sym::(\w+), &\[([^\]]+)\]\)", required)
    text += '#[rustfmt::skip]\npub(super) const REQUIRED: &[(&str, &[&str])] = &[\n'
    for parent, children in required:
        children = ', '.join(f'"{child}"' for child in re.findall(r'sym::(\w+)', children))
        text += f'    ("{parent}", &[{children}]),\n'
    text += '];\n\n'
    relative = 'compiler/rustc_ast_passes/src/feature_gate.rs'
    gates = read(relative)
    text += f'// {relative}: sha256 {hashlib.sha256(gates).hexdigest()}\n'
    for function, label in (('check_new_solver_banned_features', 'NEW_SOLVER_BANNED'),
                            ('check_features_requiring_new_solver', 'NEW_SOLVER_REQUIRED')):
        body = re.search(r'fn '+function+r'\(.*?(?=\nfn |\Z)', gates.decode(), re.S).group(0)
        if 'sess.opts.unstable_opts.next_solver.globally' not in body:
            raise ValueError(f'changed solver feature policy: {function}')
        names = re.findall(r'feat.gate_name == sym::(\w+)', body)
        if not names:
            raise ValueError(f'missing solver feature policy: {function}')
        text += f'pub(super) const {label}: &[&str] = &[' + ', '.join(f'"{name}"' for name in names) + '];\n'
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.source)
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("release feature catalog is stale")
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(generated)
