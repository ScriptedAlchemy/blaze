//! Reproduce requests, configuration and source inputs without a compiler binary.
mod common;

use std::{
    ffi::{OsStr, OsString},
    path::{Path, PathBuf},
};

use blaze_spec::{
    assemble::Spec,
    flags::{Request, Subcommand},
    platform::Probe,
    replay::{Saved, capture, prepare},
};
use blaze_wire::{SourceRef, StoreIdentity};
use common::{FakeMachine, Fixture, context, host};

fn fixture() -> Fixture {
    let f = Fixture::with_root(
        "[package]\nname='saved'\nversion='0.1.0'\nedition='2021'\n[features]\nchosen=[]\n",
    );
    f.write("src/main.rs", "fn main() { println!(\"{}\", include_str!(\"../data\")); }\n");
    f.write("data", "before");
    f.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"saved\"\nversion = \"0.1.0\"\n");
    f
}

fn saved(f: &Fixture, command: Subcommand, args: &[&str], store: &Path) -> Spec {
    let root = f.root();
    let env = f.env();
    let host = host(false);
    let args: Vec<_> = args.iter().map(|arg| (*arg).to_owned()).collect();
    let request = Request::parse(command, &args).unwrap();
    capture(&request, &args, &context(f, &env, &host, &root), store, &[]).unwrap()
}

fn prepared(made: &Spec, store: &Path, at: &Path) -> blaze_spec::replay::Prepared {
    prepare(
        &Saved::of(made).unwrap(),
        store,
        at,
        &host(false),
        StoreIdentity([9; 32]),
        &FakeMachine,
        Some(&common::rust_release),
        &[("PATH".to_owned(), OsString::from("/usr/bin"))].into_iter().collect(),
    )
    .unwrap()
}

#[test]
fn replay_execution_keeps_rooted_worker_path_only() {
    let f = fixture();
    let store = tempfile::tempdir().unwrap();
    let made = saved(&f, Subcommand::Build, &[], store.path());
    drop(f);
    let worker = tempfile::tempdir().unwrap();
    let path = std::env::join_paths([Path::new("worker-bin"), Path::new("/usr/bin")]).unwrap();
    let executor =
        [("PATH".to_owned(), path), ("WORKER_ONLY".to_owned(), OsString::from("excluded"))]
            .into_iter()
            .collect();
    let replay = prepare(
        &Saved::of(&made).unwrap(),
        store.path(),
        &worker.path().join("source"),
        &host(false),
        StoreIdentity([9; 32]),
        &FakeMachine,
        Some(&common::rust_release),
        &executor,
    )
    .unwrap();
    let expected = std::env::join_paths([
        std::env::current_dir().unwrap().join("worker-bin"),
        PathBuf::from("/usr/bin"),
    ])
    .unwrap();
    assert_eq!(replay.environment["PATH"], expected);
    let effective = replay.execution_environment().unwrap();
    assert_eq!(effective["PATH"], expected);
    assert!(!effective.contains_key("WORKER_ONLY"));
    replay.native_closure(&FakeMachine).unwrap();
}

