    let prepared = prepared(&made, store.path(), &worker.path().join("source"));
    let plans = blaze_spec::execution::programs(
        &prepared,
        Path::new("/toolchain"),
        &worker.path().join("artifacts"),
    )
    .unwrap();
    let crates = plans[0].project["crates"].as_array().unwrap();
    let app = &crates[0];
    assert_eq!(app["display_name"], "app");
    let index = app["deps"][0]["crate"].as_u64().unwrap() as usize;
    assert_eq!(app["deps"][0]["name"], "renamed");
    let dependency = &crates[index];
    assert_eq!(dependency["display_name"], "dependency");
