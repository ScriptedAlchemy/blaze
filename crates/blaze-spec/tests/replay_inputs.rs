#[test]
fn git_bundle_replays_sibling_packages_without_origin_or_cargo_home() {
    let directory = tempfile::tempdir().unwrap();
    let f = Fixture { dir: tempfile::tempdir_in(directory.path()).unwrap() };
    let repository = directory.path().join("upstream");
    let home = directory.path().join("cargo-home");
    let write = |name: &str, text: &str| {
        let path = repository.join(name);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    };
    write("Cargo.toml", "[workspace]\nmembers=['a','b']\nresolver='2'\n");
    write(
        "a/Cargo.toml",
        "[package]\nname='a'\nversion='0.1.0'\nedition='2021'\n[dependencies]\nb={path='../b'}\n",
    );
    write("a/src/lib.rs", "pub fn a()->&'static str { b::b() }\n");
    write("b/Cargo.toml", "[package]\nname='b'\nversion='0.1.0'\nedition='2021'\n");
    write("b/src/lib.rs", "pub fn b()->&'static str { include_str!(\"../data\") }\n");
    write("b/data", "captured Git source");
    let git = |args: &[&str]| {
        let output =
            std::process::Command::new("git").current_dir(&repository).args(args).output().unwrap();
        assert!(output.status.success(), "{}", String::from_utf8_lossy(&output.stderr));
        String::from_utf8(output.stdout).unwrap().trim().to_owned()
    };
    git(&["init", "-q"]);
    git(&["checkout", "-qb", "fixture"]);
    git(&["add", "."]);
    git(&[
        "-c",
        "user.name=Fixture",
        "-c",
        "user.email=fixture@example.invalid",
        "commit",
        "-qm",
        "sibling source packages",
    ]);
    let revision = git(&["rev-parse", "HEAD"]);
    let url = blaze_manifest::source::SourceId::for_path(&repository).unwrap().url;
    let source = format!("git+{url}?branch=fixture#{revision}");
    f.write("Cargo.toml", &format!("[package]\nname='app'\nversion='0.1.0'\nedition='2021'\n[dependencies]\nrenamed={{package='a',git='{url}',branch='fixture'}}\n"));
    f.write("src/main.rs", "fn main() { println!(\"{}\", renamed::a()); }\n");
    f.write("Cargo.lock", &format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\nsource = \"{source}\"\ndependencies = [\n \"b\",\n]\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"a\",\n]\n\n[[package]]\nname = \"b\"\nversion = \"0.1.0\"\nsource = \"{source}\"\n"));
    let root = f.root();
    let mut env = f.env();
    env.insert("CARGO_HOME".to_owned(), home.to_str().unwrap().to_owned());
    let host = host(false);
    let request = Request::parse(Subcommand::Run, &[]).unwrap();
    let mut ctx = context(&f, &env, &host, &root);
    ctx.offline = false;
    let store = tempfile::tempdir().unwrap();
    let made = capture(&request, &[], &ctx, store.path(), &[]).unwrap();
    assert!(home.join("git").is_dir(), "capture must exercise actual Git resolution");
    drop(f);
    drop(directory);
    assert!(!root.exists());
    assert!(!repository.exists());
    assert!(!home.exists());

    let worker = tempfile::tempdir().unwrap();
    let replay = prepared(&made, store.path(), &worker.path().join("source"));
    assert_eq!(replay.resolved.spec.build, made.build);
    let graph = &replay.resolved.graph;
    for name in ["a", "b"] {
        let package = &graph.units.iter().find(|unit| unit.package.name == name).unwrap().package;
        assert_eq!(package.source, source);
        assert!(package.manifest_dir.starts_with(&replay.root));
        assert!(!package.manifest_dir.join(".git").exists());
    }
    let plans = blaze_spec::execution::programs(
        &replay,
        Path::new("/selected/toolchain"),
        &worker.path().join("artifacts"),
    )
    .unwrap();
    assert_eq!(plans.len(), 1);
    assert!(plans[0].run);
    let crates = plans[0].project["crates"].as_array().unwrap();
    assert_eq!(crates.len(), 3);
    let app = &crates[0];
    assert_eq!(app["display_name"], "app");
    assert_eq!(app["deps"][0]["name"], "renamed");
    let a = &crates[app["deps"][0]["crate"].as_u64().unwrap() as usize];
    assert_eq!(a["display_name"], "a");
    let b = &crates[a["deps"][0]["crate"].as_u64().unwrap() as usize];
    assert_eq!(a["deps"][0]["name"], "b");
    assert_eq!(b["display_name"], "b");
    for krate in crates {
        let root_module = Path::new(krate["root_module"].as_str().unwrap());
        assert!(root_module.starts_with(&replay.root));
        assert!(root_module.is_file());
    }
    let b_root = Path::new(b["root_module"].as_str().unwrap()).parent().unwrap().parent().unwrap();
    assert_eq!(std::fs::read_to_string(b_root.join("data")).unwrap(), "captured Git source");
    assert!(!worker.path().join("resolution-home").exists());
}

#[test]
fn original_profile_inline_and_file_config_and_relative_env_are_reproduced() {
    let f = fixture();
    f.write(
        ".cargo/config.toml",
        "[env]\nASSETS={value='assets',relative=true}\nMESSAGE='configured'\n",
    );
    f.write("assets/file", "selected data");
    f.write("extra.toml", "[profile.dev]\noverflow-checks=false\n");
    let store = tempfile::tempdir().unwrap();
    let worker = tempfile::tempdir().unwrap();
    let mut env = f.env();
    env.insert("CARGO_PROFILE_DEV_OPT_LEVEL".into(), "2".into());
    env.insert("MESSAGE".into(), "request override".into());
    env.insert("PRIVATE_API_TOKEN".into(), "secret-that-must-not-persist".into());
    let args = ["--config", "extra.toml", "--config", "profile.dev.debug-assertions=true"]
        .map(str::to_owned);
    let request = Request::parse(Subcommand::Build, &args).unwrap();
    let root = f.root();
    let host = host(false);
    let made =
        capture(&request, &args, &context(&f, &env, &host, &root), store.path(), &[]).unwrap();
    assert_eq!(made.build.profile.opt_level, 2);
    assert!(made.build.profile.debug_assertions);
    assert!(!made.build.profile.overflow_checks);
    let replay = prepared(&made, store.path(), &worker.path().join("relocated"));
    assert_eq!(replay.resolved.spec.build, made.build);
    assert!(!replay.environment.contains_key("ASSETS"));
    assert!(!replay.environment.contains_key("PRIVATE_API_TOKEN"));
    let effective = replay.execution_environment().unwrap();
    assert_eq!(effective["MESSAGE"], "request override");
    assert_eq!(effective["ASSETS"], replay.cwd.join("assets").as_os_str());
    let digest: String = made.digest.iter().map(|byte| format!("{byte:02x}")).collect();
    let record = std::fs::read(store.path().join(format!("replay-{digest}.cbor"))).unwrap();
    assert!(
        !record
            .windows(b"secret-that-must-not-persist".len())
            .any(|window| window == b"secret-that-must-not-persist")
    );
}

