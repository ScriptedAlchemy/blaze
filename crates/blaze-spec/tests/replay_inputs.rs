    f.write(
        "dependency/Cargo.toml",
        "[package]\nname='dependency'\nversion='0.1.0'\nedition='2021'\n[features]\nchosen=[]\n",
    );
    f.write("dependency/src/lib.rs", "pub fn value() {}");
    f.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"dependency\",\n]\n\n[[package]]\nname = \"dependency\"\nversion = \"0.1.0\"\n");
