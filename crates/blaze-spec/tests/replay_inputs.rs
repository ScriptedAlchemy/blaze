fn fixture() -> Fixture {
    let f = Fixture::with_root(
        "[package]\nname='saved'\nversion='0.1.0'\nedition='2021'\n[features]\nchosen=[]\n",
    );
    f.write("src/main.rs", "fn main() { println!(\"{}\", include_str!(\"../data\")); }\n");
    f.write("data", "before");
    f.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"saved\"\nversion = \"0.1.0\"\n");
    f
}

fn saved(f: &Fixture, command: Subcommand, args: &[&str], store: &Path) -> Spec {
    let root = f.root();
    let env = f.env();
    let host = host(false);
    let args: Vec<_> = args.iter().map(|arg| (*arg).to_owned()).collect();
    let request = Request::parse(command, &args).unwrap();
    capture(&request, &args, &context(f, &env, &host, &root), store, &[]).unwrap()
}

fn prepared(made: &Spec, store: &Path, at: &Path) -> blaze_spec::replay::Prepared {
    prepare(
        &made.build,
        store,
        at,
        &host(false),
        StoreIdentity([9; 32]),
        &FakeMachine,
        &[("PATH".to_owned(), OsString::from("/usr/bin"))].into_iter().collect(),
    )
    .unwrap()
}

#[test]
fn dirty_inputs_survive_origin_removal_and_are_used_by_the_execution_plan() {
    let f = fixture();
    let store = tempfile::tempdir().unwrap();
    let worker = tempfile::tempdir().unwrap();
    let made =
        saved(&f, Subcommand::Run, &["--features", "chosen", "--", "original-arg"], store.path());
    f.write("src/main.rs", "compile_error!(\"must not read mutable origin\");");
    f.write("data", "after");
    let origin = f.root();
    drop(f);
    assert!(!origin.exists());
    let prepared = prepared(&made, store.path(), &worker.path().join("source"));
    assert_eq!(std::fs::read_to_string(prepared.cwd.join("data")).unwrap(), "before");
    let plans = blaze_spec::execution::programs(
        &prepared,
        Path::new("/selected/toolchain"),
        &worker.path().join("artifacts"),
    )
    .unwrap();
    assert_eq!(plans.len(), 1);
    let krate = &plans[0].project["crates"][0];
    assert!(krate["root_module"].as_str().unwrap().starts_with(prepared.root.to_str().unwrap()));
    assert!(krate["cfg"].as_array().unwrap().contains(&serde_json::json!("feature=\"chosen\"")));
    assert!(plans[0].run);
    assert_eq!(prepared.request.trailing, ["original-arg"]);
}

