//! Native probes use the request's directory without changing the serving process's cwd.
#![cfg(any(target_os = "linux", target_os = "macos"))]
mod common;

use std::{
    collections::BTreeMap,
    ffi::{OsStr, OsString},
    os::unix::{ffi::OsStringExt, fs::PermissionsExt},
    path::{Path, PathBuf},
};

use blaze_spec::{
    assemble::{Host, build_spec},
    environment,
    flags::{Request, Subcommand},
    platform::{Machine, Probe, System, exec_platform},
    run,
};
use blaze_wire::BuildSpec;

fn fixture() -> common::Fixture {
    let f = common::Fixture::with_root(
        "[package]\nname=\"probe-cwd\"\nversion=\"0.1.0\"\nedition=\"2021\"\n",
    );
    f.write("src/lib.rs", "");
    f.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"probe-cwd\"\nversion = \"0.1.0\"\n");
    f
}

fn native_host() -> Host {
    let arch = std::env::consts::ARCH;
    let os = std::env::consts::OS;
    let triple = if cfg!(target_os = "macos") {
        format!("{arch}-apple-darwin")
    } else {
        let abi = if cfg!(target_env = "musl") { "musl" } else { "gnu" };
        format!("{arch}-unknown-linux-{abi}")
    };
    Host {
        triple,
        cfg: ["unix".to_owned(), format!("target_os=\"{os}\""), format!("target_arch=\"{arch}\"")]
            .iter()
            .map(|value| value.parse().unwrap())
            .collect(),
        cpu: arch.to_owned(),
        llvm: false,
    }
}

#[test]
fn system_child_probes_receive_exactly_the_request_environment() {
    let f = fixture();
    let root = f.root();
    let compiler = root.join("request-cc");
    std::fs::write(
        &compiler,
        "#!/bin/sh\nprintf '%s:%s\\n' \"$BLAZE_PROBE_REQUEST_VALUE\" \"${HOME-unset}\"\n",
    )
    .unwrap();
    std::fs::set_permissions(&compiler, std::fs::Permissions::from_mode(0o755)).unwrap();
    let host = native_host();
    let system_path = std::env::var_os("PATH").unwrap();
    let env_tool = System.which_native(OsStr::new("env"), &system_path).unwrap();
    let mut env = BTreeMap::from([
        ("PATH".to_owned(), system_path),
        ("CC".to_owned(), compiler.into_os_string()),
    ]);
    for value in ["first request", "second request"] {
        env.insert("BLAZE_PROBE_REQUEST_VALUE".to_owned(), value.into());
        let machine =
            Machine { cwd: &root, triple: &host.triple, cpu: &host.cpu, env: &env, linker: None };
        let platform = exec_platform(&machine, &System).unwrap();
        assert_eq!(platform.cc.unwrap().1, format!("{value}:unset"));
        // Unlike a shell, env adds no variables of its own: this exercises the
        // byte-output path used for SDK lookup as well as text version probes.
        let bytes = System.run_path_in(&root, &env, &env_tool, &[]).unwrap();
        let output = String::from_utf8(bytes).unwrap();
        let got: BTreeMap<_, _> = output
            .lines()
            .map(|line| {
                let (key, value) = line.split_once('=').unwrap();
                (key.to_owned(), OsString::from(value))
            })
            .collect();
        assert_eq!(got, env);
    }
}

#[test]
fn system_probes_and_saved_replay_use_nested_request_cwd_for_tools_and_path() {
    let f = fixture();
    let root = f.root();
    // A colon in cwd cannot be prefixed to PATH and then split again.
    let cwd = root.join("nested:directory/deep");
    let process_cwd = std::env::current_dir().unwrap();
    assert_ne!(process_cwd, cwd);
    std::fs::create_dir_all(&cwd).unwrap();
    std::fs::write(cwd.join("probe-version"), "request compiler 1\n").unwrap();
    let raw_bin = OsString::from_vec(b"tools-\xff".to_vec());
    let mut bins = vec![PathBuf::new(), PathBuf::from("tools")];
    // Linux accepts arbitrary non-NUL bytes in filenames. APFS rejects this
    // spelling (EILSEQ); keep native-value tests on Mac without claiming raw
    // filesystem support there.
    #[cfg(target_os = "linux")]
    bins.push(PathBuf::from(&raw_bin));
    for bin in bins {
        std::fs::create_dir_all(cwd.join(&bin)).unwrap();
        let tool = cwd.join(bin).join("review-cc");
        std::fs::write(
            &tool,
            "#!/bin/sh\nread -r version < probe-version || exit 1\nprintf '%s\\n' \"$version\"\n",
        )
        .unwrap();
        std::fs::set_permissions(&tool, std::fs::Permissions::from_mode(0o755)).unwrap();
    }
    let system_path = std::env::var_os("PATH").unwrap();
    let prefixed = |prefix: &OsStr| {
        let mut path = prefix.to_owned();
        path.push(":");
        path.push(&system_path);
        path
    };
    let mut cases = vec![
        (OsString::from("./tools/review-cc"), system_path.clone()),
        (OsString::from("review-cc"), prefixed(OsStr::new("tools"))),
        (OsString::from("review-cc"), prefixed(OsStr::new(""))),
        (cwd.join("tools/review-cc").into_os_string(), system_path.clone()),
    ];
    #[cfg(target_os = "linux")]
    cases.push((OsString::from("review-cc"), prefixed(&raw_bin)));
    let host = native_host();
    for (cc, path) in cases {
        let mut native: BTreeMap<_, _> =
            f.env().into_iter().map(|(name, value)| (name, OsString::from(value))).collect();
        native.insert("CC".into(), cc.clone());
        native.insert("PATH".into(), path);
        let env = environment::text_view(&native).unwrap();
        let mut ctx = common::context(&f, &env, &host, &cwd);
        ctx.native_env = Some(&native);
        ctx.probe = &System;
        let made = build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).unwrap();
        let compiler = made.platform.cc.as_ref().expect("CC resolves relative to request cwd");
        assert_eq!(compiler.0, "review-cc");
        assert_eq!(compiler.1, "request compiler 1", "--version runs in request cwd");
        let saved: BuildSpec =
            blaze_wire::decode(&blaze_wire::encode(&made.build), &blaze_wire::Limits::DOCUMENTED)
                .unwrap();
        let carried = saved.script_env.iter().find(|(name, _)| name == "CC").unwrap();
        assert_eq!(
            carried.1.materialize(&root).unwrap(),
            cc,
            "probe resolution preserves identity"
        );
        let (manifest, replay_cwd) = run::locations(&saved, &root).unwrap();
        assert_eq!(replay_cwd, cwd);
        let mut matched = false;
        for candidate in run::candidates(&saved).unwrap() {
            let mut replay_native = native.clone();
            replay_native.retain(|name, _| !run::governed(name));
            replay_native.extend(candidate.env);
            let replay_env = environment::text_view(&replay_native).unwrap();
            let mut request = Request::parse(candidate.command, &candidate.args).unwrap();
            request.manifest_path = Some(manifest.clone());
            let mut replay = common::context(&f, &replay_env, &host, &replay_cwd);
            replay.native_env = Some(&replay_native);
            replay.probe = &System;
            if build_spec(&request, &replay).unwrap().build == saved {
                matched = true;
                break;
            }
        }
        assert!(matched, "saved spec must replay from the serving process's different cwd");
    }
    assert_eq!(std::env::current_dir().unwrap(), process_cwd);
}

struct SdkFiles;

impl Probe for SdkFiles {
    fn which_native(&self, name: &OsStr, path: &OsStr) -> Option<PathBuf> {
        common::FakeMachine.which_native(name, path)
    }
    fn run_native(&self, program: &Path, args: &[OsString]) -> Option<String> {
        common::FakeMachine.run_native(program, args)
    }
    fn run_path(&self, program: &Path, args: &[OsString]) -> Option<Vec<u8>> {
        common::FakeMachine.run_path(program, args)
    }
    fn which(&self, name: &str, path: &str) -> Option<PathBuf> {
        common::FakeMachine.which(name, path)
    }
    fn run(&self, program: &Path, args: &[&str]) -> Option<String> {
        common::FakeMachine.run(program, args)
    }
    fn read(&self, path: &Path) -> Option<Vec<u8>> {
        if path.ends_with("SDKSettings.json") || path.ends_with("libSystem.tbd") {
            System.read(path)
        } else {
            common::FakeMachine.read(path)
        }
    }
    fn os(&self) -> Option<String> {
        common::FakeMachine.os()
    }
}

#[test]
fn relative_sdkroot_is_read_from_request_cwd_without_rewriting_its_value() {
    let f = fixture();
    let root = f.root();
    let cwd = root.join("nested/deep");
    f.write("nested/deep/sdk/MacOSX.sdk/SDKSettings.json", "{\"Version\":\"26.1\"}");
    f.write("nested/deep/sdk/MacOSX.sdk/usr/lib/libSystem.tbd", "native stub");
    let mut env = f.env();
    env.insert("SDKROOT".into(), "sdk/MacOSX.sdk".into());
    let host = common::host(false);
    let mut ctx = common::context(&f, &env, &host, &cwd);
    ctx.probe = &SdkFiles;
    let request = Request::parse(Subcommand::Build, &[]).unwrap();
    let relative = build_spec(&request, &ctx).unwrap();
    assert_eq!(relative.platform.sdk.as_ref().unwrap().1, "26.1");
    assert!(relative.platform.native_root.is_some());
    let carried = relative.build.script_env.iter().find(|(name, _)| name == "SDKROOT").unwrap();
    assert_eq!(carried.1.text(), "sdk/MacOSX.sdk");

    env.insert(
        "SDKROOT".into(),
        cwd.join("sdk/MacOSX.sdk").into_os_string().into_string().unwrap(),
    );
    let mut ctx = common::context(&f, &env, &host, &cwd);
    ctx.probe = &SdkFiles;
    let absolute = build_spec(&request, &ctx).unwrap();
    assert_eq!(relative.platform, absolute.platform);
}
