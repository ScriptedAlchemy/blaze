#[test]
fn long_escaped_workspace_cwd_and_config_decode_under_default_budget() {
    let f = Fixture::with_root("[workspace]\nmembers=[]\n");
    let root = f.root();
    let long: PathBuf = std::iter::repeat_n("Üñïcödé dir", 170).collect();
    // macOS PATH_MAX is smaller than Linux's. A long logical env path need not
    // exist; Linux additionally exercises the real long workspace filesystem.
    let ws = if cfg!(target_os = "linux") { root.join(&long) } else { root.join("short") };
    std::fs::create_dir_all(ws.join("src")).unwrap();
    std::fs::write(
        ws.join("Cargo.toml"),
        "[package]\nname=\"long\"\nversion=\"0.1.0\"\nedition=\"2021\"\n[workspace]\n",
    )
    .unwrap();
    std::fs::write(ws.join("src/lib.rs"), "").unwrap();
    std::fs::write(ws.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"long\"\nversion = \"0.1.0\"\n").unwrap();
    std::fs::create_dir_all(ws.join(".cargo")).unwrap();
    std::fs::write(
        ws.join(".cargo/config.toml"),
        format!("[env]\nASSET={{value='{}',relative=true}}\n", long.to_str().unwrap()),
    )
    .unwrap();
    let env = f.env();
    let host = host(false);
    let mut ctx = context(&f, &env, &host, &ws);
    ctx.source_root = Some(&root);
    let spec = build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).unwrap();
    if cfg!(target_os = "linux") {
        assert!(spec.build.workspace_manifest.as_str().len() > 4096);
    }
    assert!(spec.build.config_env.as_slice()[0].1.text().len() > 4096);
    let decoded: BuildSpec =
        blaze_wire::validate_as(&blaze_wire::encode(&spec.build), &blaze_wire::Limits::default())
            .unwrap();
    assert_eq!(spec.build, decoded);
    assert_eq!(run::locations(&decoded, &root).unwrap().0, ws.join("Cargo.toml"));
    // A separate workspace-relative cwd/config of the same length uses the same typed path budget.
    let path = SourcePath::from_native(&long).unwrap();
    let mut value = decoded;
    value.cwd = path.clone();
    value.config_env = blaze_wire::Set::new(vec![(
        "ASSET".to_owned(),
        blaze_wire::ConfigEnvValue::WorkspaceRelative(path),
    )]);
    assert!(
        blaze_wire::decode::<BuildSpec>(
            &blaze_wire::encode(&value),
            &blaze_wire::Limits::default()
        )
        .is_ok()
    );
}

struct NativeProbe {
    raw: OsString,
    launcher: &'static [u8],
}
impl Probe for NativeProbe {
    fn run_native(&self, p: &Path, a: &[OsString]) -> Option<String> {
        common::FakeMachine.run_native(p, a)
    }
    fn run_path(&self, p: &Path, a: &[OsString]) -> Option<Vec<u8>> {
        common::FakeMachine.run_path(p, a)
    }
    fn which(&self, name: &str, path: &str) -> Option<PathBuf> {
        common::FakeMachine.which(name, path)
    }
    fn which_native(&self, name: &OsStr, path: &OsStr) -> Option<PathBuf> {
        std::env::split_paths(path).next().map(|dir| dir.join(name))
    }
    fn run(&self, program: &Path, args: &[&str]) -> Option<String> {
        common::FakeMachine.run(program, args)
    }
    fn read(&self, path: &Path) -> Option<Vec<u8>> {
        if path.file_name().is_some_and(|name| name.as_encoded_bytes().starts_with(b"wrapper-")) {
            return Some(self.launcher.to_vec());
        }
        if path.parent() == Some(Path::new(&self.raw)) {
            Some(b"configured compiler".to_vec())
        } else {
            common::FakeMachine.read(path)
        }
    }
    fn os(&self) -> Option<String> {
        common::FakeMachine.os()
    }
}

#[test]
fn native_probe_uses_raw_path_and_custom_wrapper_not_ambient() {
    let raw = OsString::from_vec(b"/fake/bin-\xff".to_vec());
    let probe = NativeProbe { raw: raw.clone(), launcher: b"launcher1" };
    let mut env = BTreeMap::from([("PATH".to_owned(), OsString::from("/ambient"))]);
    fn platform(env: &BTreeMap<String, OsString>, probe: &dyn Probe) -> blaze_wire::ExecPlatform {
        blaze_spec::platform::exec_platform(
            &Machine { triple: "aarch64-apple-darwin", cpu: "apple-m1", env, linker: None },
            probe,
        )
        .unwrap()
    }
    let ambient = platform(&env, &probe);
    env.insert("PATH".to_owned(), raw.clone());
    let configured = platform(&env, &probe);
    assert_ne!(ambient.cc, configured.cc);
    assert_ne!(blaze_wire::digest_of(&ambient), blaze_wire::digest_of(&configured));
    let wrapper = OsString::from_vec(b"wrapper-\xff".to_vec());
    env.insert("CC_KNOWN_WRAPPER_CUSTOM".to_owned(), wrapper.clone());
    let mut cc = wrapper;
    cc.push(" cc");
    env.insert("CC".to_owned(), cc);
    let wrapped = platform(&env, &probe);
    let changed = platform(&env, &NativeProbe { raw: raw.clone(), launcher: b"launcher2" });
    assert_eq!(wrapped.cc.as_ref().unwrap().0, changed.cc.as_ref().unwrap().0);
    assert_eq!(wrapped.cc.as_ref().unwrap().0, configured.cc.as_ref().unwrap().0);
    assert_ne!(wrapped.cc, changed.cc, "ONLY launcher bytes changed, compiler constant");
}

#[test]
fn git_path_line_removes_only_terminator_and_root_keeps_spaces() {
    let raw = b" /tmp/root-\xff \n".to_vec();
    assert_eq!(
        blaze_spec::git_path::decode_line(raw).unwrap().as_os_str().as_bytes(),
        b" /tmp/root-\xff "
    );
    let f = Fixture::new();
    let root = f.root().join(" repo space ");
    std::fs::create_dir(&root).unwrap();
    assert!(
        std::process::Command::new("git")
            .current_dir(&root)
            .args(["init", "-q"])
            .status()
            .unwrap()
            .success()
    );
    assert_eq!(blaze_spec::git_path::root(&root).unwrap(), root);
}

#[test]
fn xcrun_path_stdout_preserves_raw_sdk_bytes_separately_from_version_text() {
    struct RawSdk;
    impl Probe for RawSdk {
        fn which_native(&self, n: &OsStr, p: &OsStr) -> Option<PathBuf> {
            common::FakeMachine.which_native(n, p)
        }
        fn run_native(&self, p: &Path, a: &[OsString]) -> Option<String> {
            common::FakeMachine.run_native(p, a)
        }
        fn run_path(&self, _p: &Path, a: &[OsString]) -> Option<Vec<u8>> {
            if a.last() == Some(&OsString::from("--show-sdk-path")) {
                Some(b"/sdk/raw-\xff.sdk\n".to_vec())
            } else {
                None
            }
        }
        fn which(&self, n: &str, p: &str) -> Option<PathBuf> {
            common::FakeMachine.which(n, p)
        }
        fn run(&self, p: &Path, a: &[&str]) -> Option<String> {
            common::FakeMachine.run(p, a)
        }
        fn read(&self, p: &Path) -> Option<Vec<u8>> {
            if p.as_os_str().as_bytes().starts_with(b"/sdk/raw-\xff.sdk/") {
                Some(b"real raw sdk input".to_vec())
            } else {
                common::FakeMachine.read(p)
            }
        }
        fn os(&self) -> Option<String> {
            common::FakeMachine.os()
        }
    }
    let env = BTreeMap::from([("PATH".into(), OsString::from("/usr/bin"))]);
    let result = blaze_spec::platform::exec_platform(
        &Machine { triple: "aarch64-apple-darwin", cpu: "apple-m1", env: &env, linker: None },
        &RawSdk,
    );
    let result = result.unwrap();
    assert!(result.native_root.is_some());
    assert!(result.sdk.unwrap().0.contains('%'));
}

#[cfg(target_os = "linux")]
#[test]
fn configured_raw_root_path_changes_generated_platform_and_git_root() {
    let f = Fixture::new();
    let root = f.root().join(OsString::from_vec(b"repo-\xff ".to_vec()));
    std::fs::create_dir(&root).unwrap();
    assert!(
        std::process::Command::new("git")
            .current_dir(&root)
            .args(["init", "-q"])
            .status()
            .unwrap()
            .success()
    );
    assert_eq!(blaze_spec::git_path::root(&root).unwrap(), root);
    std::fs::create_dir(root.join("src")).unwrap();
    std::fs::write(root.join("src/lib.rs"), "").unwrap();
    std::fs::write(
        root.join("Cargo.toml"),
        "[package]\nname=\"raw\"\nversion=\"0.1.0\"\nedition=\"2021\"\n",
    )
    .unwrap();
    std::fs::write(root.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"raw\"\nversion = \"0.1.0\"\n").unwrap();
    let env = f.env();
    let host = host(false);
    let probe = NativeProbe { raw: root.join("bin").into_os_string(), launcher: b"launcher" };
    let mut ctx = context(&f, &env, &host, &root);
    ctx.probe = &probe;
    ctx.source_root = Some(&root);
    let req = Request::parse(Subcommand::Build, &[]).unwrap();
    let ambient = build_spec(&req, &ctx).unwrap();
    std::fs::create_dir(root.join(".cargo")).unwrap();
    std::fs::write(
        root.join(".cargo/config.toml"),
        "[env]\nPATH={value='bin',relative=true,force=true}\n",
    )
    .unwrap();
    let configured = build_spec(&req, &ctx).unwrap();
    assert_ne!(ambient.platform_digest, configured.platform_digest);
    assert_ne!(ambient.digest, configured.digest);
    assert_ne!(
        ambient.job_content(blaze_wire::Namespace::Main),
        configured.job_content(blaze_wire::Namespace::Main)
    );
}
