//! Free-form value budgets and native process input survive generation and serialization.
#![cfg(unix)]
mod common;
use blaze_spec::{
    assemble::build_spec,
    flags::{Request, Subcommand},
    run,
};
use blaze_wire::{BuildSpec, ConfigEnvValue};
use std::{ffi::OsString, os::unix::ffi::OsStringExt};

fn fixture() -> common::Fixture {
    let f = common::Fixture::with_root(
        "[package]\nname=\"envcase\"\nversion=\"0.1.0\"\nedition=\"2021\"\n",
    );
    f.write("src/lib.rs", "");
    f.write("Cargo.lock","# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"envcase\"\nversion = \"0.1.0\"\n");
    f
}

#[test]
fn long_values_and_rustflag_decode_but_smaller_message_budget_is_bounded() {
    let f = fixture();
    let root = f.root();
    let mut env = f.env();
    let value = "x".repeat(6000);
    for key in ["PKG_CONFIG_PATH", "LDFLAGS"] {
        env.insert(key.into(), value.clone());
    }
    env.insert("RUSTFLAGS".into(), format!("--cfg feature=\"{value}\""));
    f.write(".cargo/config.toml", &format!("[env]\nLONG={value:?}\n"));
    let host = common::host(false);
    let ctx = common::context(&f, &env, &host, &root);
    let made = build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).unwrap();
    let bytes = blaze_wire::encode(&made.build);
    assert_eq!(
        blaze_wire::decode::<BuildSpec>(&bytes, &blaze_wire::Limits::default()).unwrap(),
        made.build
    );
    assert!(made.build.rustflags.iter().any(|v| v.0.len() > 4096));
    assert!(made.build.script_env.iter().all(|(_, v)| v.text().len() > 4096));
    let small = blaze_wire::Limits { request: 4096, ..blaze_wire::Limits::default() };
    assert!(blaze_wire::validate_as::<BuildSpec>(&bytes, &small).is_err());
}

#[test]
fn raw_ambient_value_is_kept_in_config_and_script_identity() {
    let f = fixture();
    let root = f.root();
    let host = common::host(false);
    f.write(".cargo/config.toml", "[env]\nASSET={value='data',relative=true}\n");
    let text = f.env();
    let mut native: std::collections::BTreeMap<_, _> =
        text.iter().map(|(k, v)| (k.clone(), OsString::from(v))).collect();
    native.insert("UNRELATED".into(), OsString::from_vec(vec![0xff]));
    native.insert("PKG_CONFIG_PATH".into(), OsString::from_vec(vec![b'p', 0xff]));
    native.insert("ASSET".into(), OsString::from_vec(vec![b'a', 0xff]));
    let mut ctx = common::context(&f, &text, &host, &root);
    ctx.native_env = Some(&native);
    let made = build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).unwrap();
    assert!(matches!(made.build.config_env.as_slice()[0].1, ConfigEnvValue::Native(_)));
    let decoded: BuildSpec =
        blaze_wire::decode(&blaze_wire::encode(&made.build), &blaze_wire::Limits::default())
            .unwrap();
    assert_eq!(
        run::config_environment(&decoded, &root).unwrap()[0].1,
        OsString::from_vec(vec![b'a', 0xff])
    );
    let candidate = run::candidates(&decoded).unwrap().remove(0);
    assert!(
        candidate.env.contains(&("PKG_CONFIG_PATH".into(), OsString::from_vec(vec![b'p', 0xff])))
    );
    let mut replacement = native.clone();
    replacement.insert("PKG_CONFIG_PATH".into(), OsString::from("p\u{fffd}"));
    ctx.native_env = Some(&replacement);
    assert_ne!(
        made.digest,
        build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).unwrap().digest
    );
}

#[test]
fn process_collection_does_not_panic_on_raw_value() {
    const MARKER: &str = "C2_NATIVE_ENV_CHILD";
    if std::env::var_os(MARKER).is_some() {
        let env = blaze_spec::environment::native_process();
        assert_eq!(env.get("ARBITRARY"), Some(&OsString::from_vec(vec![0xff])));
        assert!(blaze_spec::environment::text_view(&env).is_ok());
        let f = fixture();
        let root = f.root();
        let text = f.env();
        let host = common::host(false);
        let mut ctx = common::context(&f, &text, &host, &root);
        ctx.native_env = Some(&env);
        assert!(build_spec(&Request::parse(Subcommand::Build, &[]).unwrap(), &ctx).is_ok());
        return;
    }
    let status = std::process::Command::new(std::env::current_exe().unwrap())
        .args(["--exact", "process_collection_does_not_panic_on_raw_value"])
        .env_clear()
        .env(MARKER, "1")
        .env("ARBITRARY", OsString::from_vec(vec![0xff]))
        .env("PATH", "/usr/bin:/bin")
        .status()
        .unwrap();
    assert!(status.success());
}
