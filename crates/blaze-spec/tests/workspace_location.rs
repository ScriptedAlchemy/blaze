//! Resolve workspaces and validate saved specs within a declared source tree.
mod common;

use blaze_spec::{
    assemble::{Spec, build_spec},
    flags::{Request, Subcommand},
    run,
};
use blaze_wire::{BuildSpec, Namespace};
use common::{Fixture, context, host};
use std::{collections::BTreeMap, path::Path};

fn git(root: &Path, args: &[&str]) -> String {
    let result = std::process::Command::new("git").current_dir(root).args(args).output().unwrap();
    assert!(result.status.success(), "{}", String::from_utf8_lossy(&result.stderr));
    String::from_utf8(result.stdout).unwrap().trim().to_owned()
}

fn oid(value: &str) -> [u8; 20] {
    std::array::from_fn(|at| u8::from_str_radix(&value[at * 2..at * 2 + 2], 16).unwrap())
}

fn repository() -> Fixture {
    let fixture = Fixture::with_root("[workspace]\nmembers=[]\n");
    for (location, body) in
        [("left", "pub fn value() -> u8 { 1 }"), ("right", "pub fn value() -> u8 { 2 }")]
    {
        fixture.write(
            &format!("{location}/Cargo.toml"),
            "[package]\nname=\"same\"\nversion=\"0.1.0\"\nedition=\"2021\"\n[workspace]\n",
        );
        fixture.write(&format!("{location}/src/lib.rs"), body);
        fixture.write(&format!("{location}/Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"same\"\nversion = \"0.1.0\"\n");
        fixture.write(&format!("{location}/nested/deep/.keep"), "");
    }
    git(&fixture.root(), &["init", "-q"]);
    git(&fixture.root(), &["add", "."]);
    // Fixture-only identity, not the lane's git identity. Both copies have identical commits.
    let status = std::process::Command::new("git")
        .current_dir(fixture.root())
        .args([
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "-qm",
            "workspace locations",
        ])
        .env("GIT_AUTHOR_DATE", "2000-01-01T00:00:00Z")
        .env("GIT_COMMITTER_DATE", "2000-01-01T00:00:00Z")
        .status()
        .unwrap();
    assert!(status.success());
    fixture
}

fn make(fixture: &Fixture, cwd: &Path, args: &[String]) -> Spec {
    let root = fixture.root();
    let env = fixture.env();
    let host = host(false);
    let mut ctx = context(fixture, &env, &host, cwd);
    ctx.source = blaze_wire::SourceRef::Git(blaze_wire::GitRef {
        repo_id: 1,
        commit: oid(&git(&root, &["rev-parse", "HEAD"])),
        tree: oid(&git(&root, &["rev-parse", "HEAD^{tree}"])),
    });
    ctx.source_root = Some(&root);
    build_spec(&Request::parse(Subcommand::Build, args).unwrap(), &ctx).unwrap()
}

#[test]
fn siblings_are_distinct_and_selected_workspace_relocation_is_equal() {
    let first = repository();
    let moved = repository();
    let left = make(&first, &first.root().join("left"), &[]);
    let right = make(&first, &first.root().join("right"), &[]);
    assert_eq!(left.build.source, right.build.source);
    assert_eq!(left.build.units, right.build.units);
    assert_eq!(left.build.cwd.as_str(), ".");
    assert_eq!(left.build.workspace_manifest.as_str(), "left/Cargo.toml");
    assert_eq!(right.build.workspace_manifest.as_str(), "right/Cargo.toml");
    assert_ne!(left.digest, right.digest);
    assert_ne!(left.job_content(Namespace::Main), right.job_content(Namespace::Main));
    assert_ne!(left.front_end, right.front_end);
    assert_ne!(left.config, right.config);
    let relocated = make(&moved, &moved.root().join("left"), &[]);
    assert_eq!(left.build, relocated.build);
    assert_eq!(left.front_end, relocated.front_end);
    assert_eq!(left.config, relocated.config);
    assert_eq!(left.job_content(Namespace::Main), relocated.job_content(Namespace::Main));
}

#[test]
fn nested_explicit_parent_manifest_and_saved_replay_use_the_selected_workspace() {
    let fixture = repository();
    let root = fixture.root();
    let cwd = root.join("left/nested/deep");
    let args = ["--manifest-path".to_owned(), "../../Cargo.toml".to_owned()];
    let original = make(&fixture, &cwd, &args);
    assert_eq!(original.build.cwd.as_str(), "nested/deep");
    assert_eq!(original.build.workspace_manifest.as_str(), "left/Cargo.toml");
    let bytes = blaze_wire::encode(&original.build);
    let saved: BuildSpec = blaze_wire::decode(&bytes, &blaze_wire::Limits::default()).unwrap();
    let (manifest, replay_cwd) = run::locations(&saved, &root).unwrap();
    assert_eq!(manifest, root.join("left/Cargo.toml"));
    assert_eq!(replay_cwd, cwd);
    assert_ne!(replay_cwd, root.join(saved.cwd.to_native().unwrap()));
    let host = host(false);
    let mut matched = false;
    for candidate in run::candidates(&saved).unwrap() {
        let mut env: BTreeMap<_, _> =
            fixture.env().into_iter().filter(|(key, _)| !run::governed(key)).collect();
        env.extend(candidate.env.into_iter().map(|(k, v)| (k, v.into_string().unwrap())));
        let mut request = Request::parse(candidate.command, &candidate.args).unwrap();
        request.manifest_path = Some(manifest.clone());
        let mut ctx = context(&fixture, &env, &host, &replay_cwd);
        ctx.source = saved.source.clone();
        ctx.source_root = Some(&root);
        let generated = build_spec(&request, &ctx).unwrap();
        if generated.build == saved {
            matched = true;
            break;
        }
    }
    assert!(matched, "the same reconstruction path used by CLI replay must validate");
}

#[test]
fn literal_and_relative_config_are_keyed_and_materialized_after_round_trip() {
    let fixture = repository();
    let root = fixture.root();
    fixture.write("left/.cargo/config.toml", "[env]\nASSET = \"data\"\n");
    let literal = make(&fixture, &root.join("left"), &[]);
    fixture
        .write("left/.cargo/config.toml", "[env]\nASSET = { value = \"data\", relative = true }\n");
    let relative = make(&fixture, &root.join("left"), &[]);
    // Dirty input snapshots remain separate work; only the env tag changes in these specs.
    assert_eq!(literal.build.source, relative.build.source);
    assert_eq!(literal.build.units, relative.build.units);
    assert_ne!(literal.digest, relative.digest);
    assert_ne!(literal.job_content(Namespace::Main), relative.job_content(Namespace::Main));
    let decode = |spec: &BuildSpec| {
        blaze_wire::decode::<BuildSpec>(&blaze_wire::encode(spec), &blaze_wire::Limits::default())
            .unwrap()
    };
    let literal = decode(&literal.build);
    let relative = decode(&relative.build);
    assert_eq!(literal.config_env.as_slice()[0].1.text(), "data");
    assert_eq!(relative.config_env.as_slice()[0].1.text(), "data");
    let worker = repository();
    assert_eq!(
        run::config_environment(&literal, &worker.root()).unwrap(),
        [("ASSET".to_owned(), std::ffi::OsString::from("data"))]
    );
    assert_eq!(
        run::config_environment(&relative, &worker.root()).unwrap(),
        [("ASSET".to_owned(), worker.root().join("left/data").into_os_string())]
    );
}

#[test]
fn saved_revalidation_covers_both_siblings_in_relocated_source() {
    let original = repository();
    let moved = repository();
    for sibling in ["left", "right"] {
        let saved = make(
            &original,
            &original.root().join(sibling).join("nested/deep"),
            &["--manifest-path".to_owned(), "../../Cargo.toml".to_owned()],
        )
        .build;
        let back: BuildSpec =
            blaze_wire::decode(&blaze_wire::encode(&saved), &blaze_wire::Limits::default())
                .unwrap();
        let (manifest, cwd) = run::locations(&back, &moved.root()).unwrap();
        assert_eq!(manifest, moved.root().join(sibling).join("Cargo.toml"));
        let root = moved.root();
        let env = moved.env();
        let host = host(false);
        let mut matched = false;
        for candidate in run::candidates(&back).unwrap() {
            let mut request = Request::parse(candidate.command, &candidate.args).unwrap();
            request.manifest_path = Some(manifest.clone());
            let mut vars = env.clone();
            vars.extend(candidate.env.into_iter().map(|(k, v)| (k, v.into_string().unwrap())));
            let mut ctx = context(&moved, &vars, &host, &cwd);
            ctx.source = back.source.clone();
            ctx.source_root = Some(&root);
            if build_spec(&request, &ctx).unwrap().build == back {
                matched = true;
                break;
            }
        }
        assert!(matched);
    }
}
