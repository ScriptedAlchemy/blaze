//! Invocation witnesses restore resolution inputs without inheriting worker compiler settings.

mod common;

use std::{collections::BTreeMap, ffi::OsString, path::Path};

use blaze_spec::{
    assemble::{Spec, build_spec},
    environment,
    flags::{Request, Subcommand},
    recipe::{ConfigFile, ReplayRecipe},
};
use blaze_wire::{
    BuildSpec, ConfigEnvValue, Encoder, ErrorKind, Limits, NativeValue, SourcePath, Wire,
    digest_of, encode,
};
use common::{Fixture, context, host};

fn words(words: &[&str]) -> Vec<String> {
    words.iter().map(|word| (*word).to_owned()).collect()
}

fn native(env: &[(&str, &str)]) -> BTreeMap<String, OsString> {
    env.iter().map(|(name, value)| ((*name).to_owned(), OsString::from(value))).collect()
}

fn plain() -> BuildSpec {
    let fixture = Fixture::new();
    common::spec(&fixture, &fixture.env(), Subcommand::Build, &[], None).unwrap().build
}

fn fixture() -> Fixture {
    let fixture = Fixture::with_manifest("[profile.quick]\ninherits='dev'\n");
    fixture.write(
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"b\"\nversion = \"0.1.0\"\n",
    );
    fixture
}

fn resolve(fixture: &Fixture, args: &[String], native: &BTreeMap<String, OsString>) -> Spec {
    let root = fixture.root();
    let mut env = environment::text_view(native).unwrap();
    env.insert("__CARGO_TEST_ROOT".into(), root.to_str().unwrap().to_owned());
    let host = host(false);
    let request = Request::parse(Subcommand::Build, args).unwrap();
    let mut ctx = context(fixture, &env, &host, &root);
    ctx.source_root = Some(&root);
    ctx.native_env = Some(native);
    build_spec(&request, &ctx).unwrap()
}

#[test]
fn original_cli_profiles_config_and_env_resolve_again_under_hostile_ambient() {
    let fixture = fixture();
    fixture.write("cfg/profile.toml", "[profile.quick]\ndebug=1\n");
    let original = words(&[
        "--profile=quick",
        "--config",
        "cfg/profile.toml",
        "--config=profile.quick.opt-level=2",
        "-p",
        "a",
    ]);
    let mut env: BTreeMap<_, _> =
        fixture.env().into_iter().map(|(name, value)| (name, value.into())).collect();
    env.extend(native(&[
        ("CARGO_PROFILE_QUICK_DEBUG_ASSERTIONS", "false"),
        ("CARGO_BUILD_RUSTFLAGS", "--cfg recipe"),
        ("RA_JIT_MIR_OPT", "1"),
    ]));
    let made = resolve(&fixture, &original, &env);
    assert_eq!(made.build.profile.name, "quick");
    assert_eq!(made.build.profile.opt_level, 2);
    assert!(!made.build.profile.debug_assertions);
    assert_eq!(
        made.build.rustflags.iter().map(|flag| flag.0.as_str()).collect::<Vec<_>>(),
        ["--cfg=recipe"]
    );
    let recipe = ReplayRecipe::capture(
        &made.build,
        Subcommand::Build,
        &original,
        &env,
        &[ConfigFile { argument: 1, path: SourcePath::new("cfg/profile.toml".into()).unwrap() }],
    )
    .unwrap();
    let mut hostile = native(&[
        ("HOME", "/worker/home"),
        ("PATH", "/worker/tools"),
        ("CARGO_PROFILE_QUICK_OPT_LEVEL", "0"),
        ("CARGO_PROFILE_QUICK_DEBUG_ASSERTIONS", "true"),
        ("CARGO_BUILD_RUSTFLAGS", "--cfg hostile"),
        ("CARGO_TARGET_UNLISTED_RUSTFLAGS", "--cfg hostile"),
        ("CARGO_FUTURE_CONFIG_KEY", "hostile"),
        ("CARGO_HTTP_PROXY", "hostile"),
        ("CARGO_ENCODED_RUSTFLAGS", "--cfg\u{1f}hostile"),
        ("RUSTFLAGS", "--cfg hostile"),
        ("RUSTDOCFLAGS", "--cfg hostile"),
        ("RUSTC", "/hostile/rustc"),
        ("RUSTDOC", "/hostile/rustdoc"),
        ("RA_JIT_BACKEND", "llvm"),
        ("RA_JIT_MIR_OPT", "0"),
        ("RA_JIT_ANSWERS", "rustc"),
        ("CC", "/hostile/cc"),
        ("UNRELATED", "hostile"),
        ("RA_JIT_MEMORY_MAX", "16G"),
        ("RA_JIT_RUN_ID", "watchdog"),
    ]);
    hostile.insert("CARGO_HOME".into(), env["CARGO_HOME"].clone());
    let replay = recipe.materialize(&made.build, &fixture.root(), &hostile).unwrap();
    let args: Vec<String> =
        replay.args.into_iter().map(|word| word.into_string().unwrap()).collect();
    let again = resolve(&fixture, &args, &replay.env);
    assert_eq!(again.build, made.build);
    for key in [
        "RUSTC",
        "RUSTDOC",
        "RUSTFLAGS",
        "RUSTDOCFLAGS",
        "CARGO_ENCODED_RUSTFLAGS",
        "CARGO_TARGET_UNLISTED_RUSTFLAGS",
        "CARGO_FUTURE_CONFIG_KEY",
        "CARGO_HTTP_PROXY",
        "CARGO_PROFILE_QUICK_OPT_LEVEL",
        "RA_JIT_BACKEND",
        "RA_JIT_ANSWERS",
        "CC",
        "UNRELATED",
    ] {
        assert!(!replay.env.contains_key(key), "{key}");
    }
    assert_eq!(replay.env["RA_JIT_MEMORY_MAX"], "16G");
    assert_eq!(replay.env["RA_JIT_RUN_ID"], "watchdog");
    assert_eq!(recipe.original_words().collect::<Vec<_>>(), original);
}

#[test]
fn equivalent_spellings_have_separate_recipes_and_the_same_spec_and_job() {
    let fixture = fixture();
    let env: BTreeMap<String, OsString> =
        fixture.env().into_iter().map(|(name, value)| (name, value.into())).collect();
    let cli = words(&["--config", "profile.dev.opt-level=1"]);
    let mut from_env = env.clone();
    from_env.insert("CARGO_PROFILE_DEV_OPT_LEVEL".into(), "1".into());
    let a = resolve(&fixture, &cli, &env);
    let b = resolve(&fixture, &[], &from_env);
    assert_eq!(a.build, b.build);
    assert_eq!(
        a.job_content(blaze_wire::Namespace::Main),
        b.job_content(blaze_wire::Namespace::Main)
    );
    let before = encode(&a.build);
    let a_recipe = ReplayRecipe::capture(&a.build, Subcommand::Build, &cli, &env, &[]).unwrap();
    let b_recipe = ReplayRecipe::capture(&b.build, Subcommand::Build, &[], &from_env, &[]).unwrap();
    assert_ne!(digest_of(&a_recipe), digest_of(&b_recipe));
    assert_eq!(a_recipe.spec_digest(), b_recipe.spec_digest());
    assert_eq!(before, encode(&a.build));

    let release = resolve(&fixture, &words(&["--release"]), &env);
    let named = resolve(&fixture, &words(&["--profile=release"]), &env);
    assert_eq!(release.build, named.build);
    let a =
        ReplayRecipe::capture(&release.build, Subcommand::Build, &words(&["--release"]), &env, &[])
            .unwrap();
    let b = ReplayRecipe::capture(
        &named.build,
        Subcommand::Build,
        &words(&["--profile=release"]),
        &env,
        &[],
    )
    .unwrap();
    assert_ne!(encode(&a), encode(&b));
}

