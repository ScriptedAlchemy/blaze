#[test]
fn file_config_bindings_are_explicit_and_never_guessed_from_spelling() {
    let spec = plain();
    let env = BTreeMap::new();
    let original = words(&["--config=old/file=dev.toml", "--config", "profile.dev.debug=1"]);
    let files = [ConfigFile {
        argument: 0,
        path: SourcePath::from_native(Path::new("cfg/file=dev.toml")).unwrap(),
    }];
    let recipe = ReplayRecipe::capture(&spec, Subcommand::Build, &original, &env, &files).unwrap();
    let replay = recipe.materialize(&spec, Path::new("/image"), &env).unwrap();
    assert_eq!(
        replay.args[2..],
        ["--config", "/image/cfg/file=dev.toml", "--config", "profile.dev.debug=1"]
            .map(OsString::from)
    );
    assert_eq!(recipe.original_words().collect::<Vec<_>>(), original);
    assert!(
        ReplayRecipe::capture(
            &spec,
            Subcommand::Build,
            &words(&["--config", "missing.toml"]),
            &env,
            &[]
        )
        .is_err()
    );
    for argument in [2, 100] {
        let wrong = [ConfigFile { argument, path: files[0].path.clone() }];
        assert!(ReplayRecipe::capture(&spec, Subcommand::Build, &original, &env, &wrong).is_err());
        assert!(
            ReplayRecipe::decode(&raw(1, 1, &original, &[], &wrong), &Limits::default()).is_err()
        );
    }
    let missing_first = words(&["--config=old/file.toml", "--config", "profile.dev.debug=1"]);
    let second = [ConfigFile { argument: 1, path: files[0].path.clone() }];
    assert!(
        ReplayRecipe::capture(&spec, Subcommand::Build, &missing_first, &env, &second).is_err()
    );
    assert!(
        ReplayRecipe::decode(&raw(1, 1, &missing_first, &[], &second), &Limits::default()).is_err()
    );
    let ambiguous = words(&["--config=profile.dev.opt-level=1", "--config", "profile.dev.debug=1"]);
    let recipe =
        ReplayRecipe::capture(&spec, Subcommand::Build, &ambiguous, &env, &second).unwrap();
    let replay = recipe.materialize(&spec, Path::new("/image"), &env).unwrap();
    assert_eq!(
        replay.args[2..],
        ["--config=profile.dev.opt-level=1", "--config", "/image/cfg/file=dev.toml"]
            .map(OsString::from)
    );
    assert_eq!(recipe.original_words().collect::<Vec<_>>(), ambiguous);
    assert!(
        ReplayRecipe::capture(
            &spec,
            Subcommand::Build,
            &original,
            &env,
            &[files[0].clone(), files[0].clone()]
        )
        .is_err()
    );
}

