#[cfg(unix)]
#[test]
fn saved_manifest_cwd_and_file_bindings_materialize_without_lossy_paths() {
    use std::os::unix::ffi::OsStringExt;
    let mut spec = plain();
    spec.workspace_manifest = SourcePath::new("ws/Cargo.toml".into()).unwrap();
    spec.cwd = SourcePath::new("nested".into()).unwrap();
    let original = words(&[
        "--manifest-path=/requester/ws/Cargo.toml",
        "--manifest-path",
        "other/Cargo.toml",
        "--config",
        "old.toml",
    ]);
    let files = [ConfigFile { argument: 3, path: SourcePath::new("cfg/%FF.toml".into()).unwrap() }];
    let recipe =
        ReplayRecipe::capture(&spec, Subcommand::Build, &original, &BTreeMap::new(), &files)
            .unwrap();
    let root = std::path::PathBuf::from(OsString::from_vec(b"/image-\xff".to_vec()));
    let replay = recipe.materialize(&spec, &root, &BTreeMap::new()).unwrap();
    assert_eq!(replay.manifest, root.join("ws/Cargo.toml"));
    assert_eq!(replay.cwd, root.join("ws/nested"));
    assert_eq!(
        replay.args,
        vec![
            OsString::from("--manifest-path"),
            root.join("ws/Cargo.toml").into_os_string(),
            OsString::from("--config"),
            root.join(OsString::from_vec(b"cfg/\xff.toml".to_vec())).into_os_string()
        ]
    );
    assert_eq!(recipe.original_words().collect::<Vec<_>>(), original);
}

#[test]
fn canonical_cbor_roundtrip_and_format_one_vector() {
    let spec = plain();
    let recipe =
        ReplayRecipe::capture(&spec, Subcommand::Build, &[], &BTreeMap::new(), &[]).unwrap();
    let bytes = encode(&recipe);
    let mut expected = vec![0xa6, 0, 1, 1, 0x58, 0x20];
    expected.extend(digest_of(&spec));
    expected.extend([2, 1, 3, 0x80, 4, 0x80, 5, 0x80]);
    assert_eq!(bytes, expected);
    let decoded = ReplayRecipe::decode(&bytes, &Limits::default()).unwrap();
    assert_eq!(decoded, recipe);
    assert_eq!(encode(&decoded), bytes);
    assert_eq!(digest_of(&decoded), digest_of(&recipe));
    let mut different_command = bytes.clone();
    different_command[39] = 0;
    let changed_recipe = ReplayRecipe::decode(&different_command, &Limits::default()).unwrap();
    assert!(changed_recipe.materialize(&spec, Path::new("/image"), &BTreeMap::new()).is_err());
    let mut changed = spec.clone();
    changed.cwd = SourcePath::new("elsewhere".into()).unwrap();
    assert!(decoded.materialize(&changed, Path::new("/image"), &BTreeMap::new()).is_err());
}

fn raw(
    version: u32,
    command: u8,
    words: &[String],
    env: &[(String, ConfigEnvValue)],
    files: &[ConfigFile],
) -> Vec<u8> {
    let mut e = Encoder::new();
    e.map(6);
    e.uint(0);
    version.encode(&mut e);
    e.uint(1);
    [0u8; 32].encode(&mut e);
    e.uint(2);
    command.encode(&mut e);
    e.uint(3);
    words.to_vec().encode(&mut e);
    e.uint(4);
    env.to_vec().encode(&mut e);
    e.uint(5);
    files.to_vec().encode(&mut e);
    e.into_bytes()
}

#[test]
fn decoder_rejects_missing_unknown_duplicate_and_noncanonical_fields() {
    let valid = raw(1, 1, &[], &[], &[]);
    let mut missing = valid[..valid.len() - 2].to_vec();
    missing[0] = 0xa5;
    assert_eq!(
        ReplayRecipe::decode(&missing, &Limits::default()).unwrap_err().kind,
        ErrorKind::MissingKey(5)
    );
    let mut unknown = valid.clone();
    unknown[0] = 0xa7;
    unknown.extend([6, 0]);
    assert_eq!(
        ReplayRecipe::decode(&unknown, &Limits::default()).unwrap_err().kind,
        ErrorKind::UnknownKey(6)
    );
    let mut duplicate = valid.clone();
    duplicate[0] = 0xa7;
    duplicate.extend([5, 0x80]);
    assert!(matches!(
        ReplayRecipe::decode(&duplicate, &Limits::default()).unwrap_err().kind,
        ErrorKind::DuplicateKey(_)
    ));
    let mut nonshortest = valid.clone();
    nonshortest.splice(2..3, [0x18, 1]);
    assert_eq!(
        ReplayRecipe::decode(&nonshortest, &Limits::default()).unwrap_err().kind,
        ErrorKind::NonShortestHead
    );
    let mut trailing = valid.clone();
    trailing.push(0);
    assert_eq!(
        ReplayRecipe::decode(&trailing, &Limits::default()).unwrap_err().kind,
        ErrorKind::TrailingBytes
    );
    for malformed in [&valid[..valid.len() - 1], b"{}", &[0xbf, 0xff]] {
        assert!(ReplayRecipe::decode(malformed, &Limits::default()).is_err());
    }
    for (version, command) in [(0, 1), (2, 1), (1, 4)] {
        assert!(
            ReplayRecipe::decode(&raw(version, command, &[], &[], &[]), &Limits::default())
                .is_err()
        );
    }
}

#[test]
fn decoder_enforces_request_collection_name_and_native_budgets() {
    let data = raw(1, 1, &[], &[], &[]);
    let limits = Limits { request: data.len() as u32 - 1, ..Limits::default() };
    assert!(matches!(
        ReplayRecipe::decode(&data, &limits).unwrap_err().kind,
        ErrorKind::OversizeItem { .. }
    ));
    let many = raw(1, 1, &vec!["-v".into(); 7], &[], &[]);
    let limits = Limits { batch_items: 6, ..Limits::default() };
    assert!(matches!(
        ReplayRecipe::decode(&many, &limits).unwrap_err().kind,
        ErrorKind::OversizeItem { .. }
    ));
    let env = [("CARGO_BUILD_JOBS".into(), ConfigEnvValue::Literal("1".to_owned().into()))];
    let limits = Limits { string: 3, ..Limits::default() };
    assert!(matches!(
        ReplayRecipe::decode(&raw(1, 1, &[], &env, &[]), &limits).unwrap_err().kind,
        ErrorKind::OversizeItem { .. }
    ));
    let env = [("CARGO_BUILD_JOBS".into(), ConfigEnvValue::Native(NativeValue(vec![0xff; 65])))];
    let limits = Limits { request: 64, ..Limits::default() };
    assert!(ReplayRecipe::decode(&raw(1, 1, &[], &env, &[]), &limits).is_err());
}

