//! Original spelling and executor cache locations are replay hints, not build identity.

mod common;

use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

use blaze_spec::{
    assemble::{Context, Spec},
    flags::{Request, Subcommand},
    replay,
};
use blaze_wire::{RootRef, SourceRef, StoreIdentity};

struct Project {
    directory: tempfile::TempDir,
    root: PathBuf,
    cargo_home: PathBuf,
    store: PathBuf,
}

impl Project {
    fn new(checkout: &str, cargo_home: &str) -> Self {
        let directory = tempfile::tempdir().unwrap();
        let root = directory.path().join(checkout);
        let home = directory.path().join(cargo_home);
        let project = Self {
            root,
            cargo_home: home,
            store: directory.path().join("replay-store"),
            directory,
        };
        std::fs::create_dir_all(&project.cargo_home).unwrap();
        project.write("Cargo.toml", "[package]\nname='identity'\nversion='0.1.0'\nedition='2021'\n[features]\nfirst=[]\nsecond=[]\n");
        project.write("src/main.rs", "fn main() {}\n");
        project.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"identity\"\nversion = \"0.1.0\"\n");
        project
    }

    fn write(&self, name: &str, contents: &str) {
        let path = self.root.join(name);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, contents).unwrap();
    }

    fn capture(&self, words: &[&str], extra: &[(&str, &str)]) -> Spec {
        let words: Vec<String> = words.iter().map(|word| (*word).to_owned()).collect();
        let request = Request::parse(Subcommand::Build, &words).unwrap();
        let mut env = BTreeMap::from([
            ("PATH".to_owned(), "/usr/bin".to_owned()),
            ("CARGO_HOME".to_owned(), self.cargo_home.to_str().unwrap().to_owned()),
            ("__CARGO_TEST_ROOT".to_owned(), self.root.to_str().unwrap().to_owned()),
        ]);
        env.extend(extra.iter().map(|(name, value)| ((*name).to_owned(), (*value).to_owned())));
        let host = common::host(true);
        let context = Context {
            native_env: None,
            source_root: None,
            cwd: &self.root,
            env: &env,
            host: &host,
            source: SourceRef::Root(RootRef { root: [0; 32] }),
            toolchain: StoreIdentity([9; 32]),
            offline: true,
            store: None,
            probe: &common::FakeMachine,
        };
        replay::capture(&request, &words, &context, &self.store, &[]).unwrap()
    }
}

fn same_identity(before: &Spec, after: &Spec) {
    assert_eq!(
        before.build.source, after.build.source,
        "the source image must not contain original invocation spelling"
    );
    assert_eq!(before.build, after.build, "equivalent requests must reproduce the same BuildSpec");
    assert_eq!(before.digest, after.digest);
    assert_eq!(before.front_end, after.front_end);
    assert_eq!(before.config, after.config);
}

#[test]
fn equivalent_profile_feature_and_transport_flags_keep_one_identity() {
    let project = Project::new("checkout", "external-home");
    for (left, right) in [
        (&[][..], &["--profile", "dev"][..]),
        (&["--release"][..], &["--profile=release"][..]),
        (&["--features", "first,second"][..], &["--features=second,first"][..]),
        (&["--offline", "--locked"][..], &["--frozen"][..]),
    ] {
        same_identity(&project.capture(left, &[]), &project.capture(right, &[]));
    }
}

#[test]
fn equivalent_rustflags_encodings_keep_one_identity() {
    let project = Project::new("checkout", "external-home");
    let separated = project.capture(&[], &[("RUSTFLAGS", "-C opt-level=2 --cfg replay_identity")]);
    let encoded = project
        .capture(&[], &[("CARGO_ENCODED_RUSTFLAGS", "-Copt-level=2\u{1f}--cfg=replay_identity")]);
    same_identity(&separated, &encoded);
}

#[test]
fn equivalent_profile_environment_and_inline_config_keep_one_identity() {
    let project = Project::new("checkout", "external-home");
    let environment = project.capture(&[], &[("CARGO_PROFILE_DEV_OPT_LEVEL", "2")]);
    let inline = project.capture(&["--config", "profile.dev.opt-level=2"], &[]);
    same_identity(&environment, &inline);
}

#[test]
fn empty_compiler_wrappers_are_the_same_as_unset_wrappers() {
    let project = Project::new("checkout", "external-home");
    let ordinary = project.capture(&[], &[]);
    let cleared = project.capture(&[], &[("RUSTC_WRAPPER", ""), ("RUSTC_WORKSPACE_WRAPPER", "")]);
    same_identity(&ordinary, &cleared);
}

#[test]
fn configured_script_variables_do_not_become_new_ambient_overrides_on_replay() {
    let project = Project::new("checkout", "external-home");
    project
        .write(".cargo/config.toml", "[env]\nCFLAGS='-DFROM_CONFIG'\nRUSTFLAGS='-Copt-level=2'\n");
    let spec = project.capture(&[], &[]);
    assert!(
        spec.build.script_env.is_empty(),
        "configuration values are keyed as config_env, not invented ambient script inputs"
    );
    assert_eq!(spec.build.config_env.len(), 2);
}

#[test]
fn equal_sign_config_filenames_follow_actual_file_resolution() {
    let project = Project::new("checkout", "external-home");
    project.write("cfg=dev.toml", "[profile.dev]\nopt-level=2\n");
    let file = project.capture(&["--features", "first", "--config", "cfg=dev.toml"], &[]);
    let attached = project.capture(&["--features=first", "--config=cfg=dev.toml"], &[]);
    let inline =
        project.capture(&["--features", "first", "--config", "profile.dev.opt-level=2"], &[]);
    same_identity(&file, &attached);
    same_identity(&file, &inline);
}

#[test]
fn empty_external_cargo_home_and_checkout_locations_do_not_enter_source_identity() {
    let first = Project::new("checkout-one", "cargo-home-one");
    let second = Project::new("nested/checkout-two", "elsewhere/deeper/cargo-home-two");
    assert_ne!(first.directory.path(), second.directory.path());
    assert!(!first.cargo_home.starts_with(&first.root));
    assert!(!second.cargo_home.starts_with(&second.root));
    assert_eq!(std::fs::read_dir(&first.cargo_home).unwrap().count(), 0);
    assert_eq!(std::fs::read_dir(&second.cargo_home).unwrap().count(), 0);
    let first_spec = first.capture(&[], &[]);
    let second_spec = second.capture(&[], &[]);
    same_identity(&first_spec, &second_spec);
    assert_eq!(first_spec.build.workspace_manifest.to_native().unwrap(), Path::new("Cargo.toml"));
}

#[test]
fn relative_cargo_home_retains_the_configuration_actually_read() {
    let project = Project::new("checkout", "external-home");
    std::fs::write(project.cargo_home.join("config.toml"), "[profile.dev]\nopt-level=2\n").unwrap();
    let absolute = project.capture(&[], &[]);
    let relative = project.capture(&[], &[("CARGO_HOME", "../external-home")]);
    same_identity(&absolute, &relative);
    assert_eq!(relative.build.profile.opt_level, 2);
}

#[test]
fn selected_member_manifest_and_package_selection_keep_one_identity() {
    let project = Project::new("checkout", "external-home");
    project.write(
        "Cargo.toml",
        "[workspace]\nmembers=['a','b']\ndefault-members=['a']\nresolver='2'\n",
    );
    std::fs::remove_dir_all(project.root.join("src")).unwrap();
    for package in ["a", "b"] {
        project.write(
            &format!("{package}/Cargo.toml"),
            &format!("[package]\nname='{package}'\nversion='0.1.0'\nedition='2021'\n"),
        );
        project.write(&format!("{package}/src/main.rs"), "fn main() {}\n");
    }
    project.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"b\"\nversion = \"0.1.0\"\n");
    let manifest = project.capture(&["--manifest-path", "b/Cargo.toml"], &[]);
    let package = project.capture(&["--package", "b"], &[]);
    same_identity(&manifest, &package);
    assert!(manifest.build.units.iter().all(|unit| unit.package.0 == "b"));
}
