"""Generate the selected C declarations from the pinned LLVM headers, using Clang's AST.

One JSON input: {"prefix": "...", "clang": "clang", "check": false}.
Unknown C types stop generation. No registry bindings or third-party Python packages.
"""
from dataclasses import dataclass
import json
from pathlib import Path
import subprocess
import sys


@dataclass(frozen=True)
class Args:
    prefix: str
    clang: str = "clang"
    check: bool = False


def walk(node):
    yield node
    for child in node.get("inner", []):
        yield from walk(child)


def main():
    args = Args(**json.loads(sys.argv[1]))
    here = Path(__file__).resolve().parent
    prefix = Path(args.prefix).resolve()
    pin = json.loads((here / "../../pins/llvm.json").read_text())
    marker = json.loads((prefix / "blaze-llvm.json").read_text())
    for key in ("version", "commit"):
        if marker[key] != pin[key]:
            raise ValueError(f"{prefix}: {key} is not pins/llvm.json's {pin[key]}")
    result = subprocess.run(
        [args.clang, "-x", "c", "-I", str(prefix / "include"), "-Xclang",
         "-ast-dump=json", "-fsyntax-only", str(here / "abi.h")],
        check=True, capture_output=True, text=True, timeout=60,
    )
    ast = json.loads(result.stdout)
    nodes = {n["id"]: n for n in walk(ast) if "id" in n and "kind" in n}
    typedefs = {n["name"]: n for n in ast["inner"] if n["kind"] == "TypedefDecl"}
    functions = {n["name"]: n for n in ast["inner"] if n["kind"] == "FunctionDecl"}
    definitions = {}
    enum_checks = []
    primitive = {"void": "core::ffi::c_void", "char": "core::ffi::c_char",
                 "int": "core::ffi::c_int", "unsigned int": "core::ffi::c_uint",
                 "size_t": "usize"}

    def rust_type(c):
        c = c.strip()
        if c.endswith("*"):
            pointee = c[:-1].strip()
            const = pointee.startswith("const ")
            return ("*const " if const else "*mut ") + rust_type(pointee.removeprefix("const "))
        if c in primitive:
            return primitive[c]
        if c.startswith("struct "):
            name = c.removeprefix("struct ")
            definitions[name] = f"#[repr(C)]\npub struct {name} {{ _private: [u8; 0] }}\n"
            return name
        if c in typedefs:
            if c not in definitions:
                node = typedefs[c]
                kind = node["type"]["qualType"]
                if kind.startswith("enum "):
                    tag = next(n["ownedTagDecl"]["id"] for n in walk(node) if "ownedTagDecl" in n)
                    rows, value = [], -1
                    for variant in nodes[tag]["inner"]:
                        if variant["kind"] != "EnumConstantDecl":
                            continue
                        values = [n["value"] for n in walk(variant) if n["kind"] == "ConstantExpr"]
                        value = int(values[0]) if values else value + 1
                        rows.append(f"    {variant['name']} = {value},")
                        enum_checks.append(f"static_assert({variant['name']} == {value});")
                    enum_checks.append(f"static_assert(sizeof({c}) == sizeof(int));")
                    definitions[c] = "#[repr(C)]\n#[derive(Clone, Copy)]\npub enum " + c + " {\n" + "\n".join(rows) + "\n}\n"
                else:
                    definitions[c] = f"pub type {c} = {rust_type(kind)};\n"
            return c
        raise ValueError(f"unhandled C type: {c}")

    declarations = []
    checks = ['// Generated by generate.py; checked against the installed pinned headers.',
              '#include "abi.h"', '#include <type_traits>']
    for name in (here / "functions.txt").read_text().split():
        node = functions[name]
        result = node["type"]["qualType"].split("(")[0].strip()
        params = [n for n in node.get("inner", []) if n["kind"] == "ParmVarDecl"]
        parameters = ", ".join(f"arg{i}: {rust_type(n['type']['qualType'])}" for i, n in enumerate(params))
        returns = "" if result == "void" else " -> " + rust_type(result)
        declarations.append(f"    pub fn {name}({parameters}){returns};")
        c_parameters = ", ".join(n['type']['qualType'] for n in params)
        checks.append(f"static_assert(std::is_same_v<decltype(&{name}), {result} (*)({c_parameters})>);")
    text = ("//! Generated by generate.py from abi.h and functions.txt.\n"
            f"//! LLVM {pin['version']}, commit {pin['commit']}.\n"
            "#![no_std]\n#![allow(non_camel_case_types, non_snake_case)]\n\n"
            + "\n".join(definitions.values()) + '\nunsafe extern "C" {\n'
            + "\n".join(declarations) + "\n}\n")
    for output, content in [(here / "src/lib.rs", text), (here / "abi-checks.cpp", "\n".join(checks + enum_checks) + "\n")]:
        if args.check:
            if output.read_text() != content:
                raise ValueError(f"{output}: regenerate from the pinned headers")
        else:
            output.parent.mkdir(exist_ok=True)
            output.write_text(content)


if __name__ == "__main__":
    main()
