#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rust_1_99_status_and_release_order_are_pinned() {
        assert_eq!(ACTIVE_LANG.len(), 188);
        assert_eq!(ACCEPTED_LANG.len(), 211);
        assert_eq!(REMOVED_LANG.len(), 103);
        assert_eq!(PROC_MACRO_LIB.len(), 10);
        for table in [ACTIVE_LANG, ACCEPTED_LANG, REMOVED_LANG, PROC_MACRO_LIB] {
            assert!(table.windows(2).all(|pair| pair[0] < pair[1]));
        }
        assert_eq!(classify("never_type"), Status::Active);
        assert_eq!(classify("test_accepted_feature"), Status::Accepted);
        assert_eq!(classify("never_type_fallback"), Status::Removed);
        assert_eq!(classify("proc_macro_span"), Status::Active);
        assert_eq!(classify("not_a_rust_feature_199"), Status::Unknown);
    }
}
