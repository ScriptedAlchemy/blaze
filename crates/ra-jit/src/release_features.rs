//! Rust 1.99.0 compiler feature gates, pinned to the release source.
//!
//! The language tables are complete for rustc 1.99.0. The library table here
//! covers the proc_macro interface required by the owned compiler bootstrap.
//! Other library features require further release metadata and are refused,
//! never silently accepted by a probe.
//!
//! Source blobs from rust-lang/rust tag 1.99.0:
//! compiler/rustc_feature/src/unstable.rs: f5b1e9d09b443cf4018942aae881f17b89511199
//! compiler/rustc_feature/src/accepted.rs: f7bb531eda374c78cda8c40140536c4706c4776a
//! compiler/rustc_feature/src/removed.rs: 43de680bfa74754abd1ffef3007b424aa81e5531
//! library/proc_macro/src/lib.rs: 2f026fb81ee1ba3bb4cdceda33aa43feefdca75e

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Status {
    Active,
    Accepted,
    Removed,
    Unknown,
}

pub(super) fn classify(name: &str) -> Status {
    if ACTIVE_LANG.binary_search(&name).is_ok() || PROC_MACRO_LIB.binary_search(&name).is_ok() {
        Status::Active
    } else if ACCEPTED_LANG.binary_search(&name).is_ok() {
        Status::Accepted
    } else if REMOVED_LANG.binary_search(&name).is_ok() {
        Status::Removed
    } else {
        Status::Unknown
    }
}

