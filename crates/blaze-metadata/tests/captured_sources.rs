//! A captured source list replaces registry/Git transport, while the lock's exact
//! identities and the native resolver remain the authority for the resulting graph.

use std::{
    path::{Path, PathBuf},
    time::{SystemTime, UNIX_EPOCH},
};

use blaze_metadata::units::{Command, TargetFilter, UnitGraph, UnitsAsked, unit_graph_captured};
use blaze_metadata::{Asked, Build, CapturedSource, TargetPlatform};

struct Scratch(PathBuf);

impl Scratch {
    fn new(label: &str) -> Self {
        let nonce = SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos();
        let root = std::env::temp_dir()
            .join(format!("blaze-captured-{label}-{}-{nonce}", std::process::id()));
        std::fs::create_dir(&root).unwrap();
        Self(root)
    }

    fn write(&self, relative: &str, text: &str) {
        let path = self.0.join(relative);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn graph(
    root: &Path,
    home: &Path,
    offline: bool,
    captured: Option<&[CapturedSource]>,
) -> anyhow::Result<(UnitGraph, Vec<(PathBuf, Vec<u8>)>, Vec<CapturedSource>)> {
    let asked = Asked {
        cargo_home: Some(home.to_owned()),
        cwd: root,
        env: vec![("__CARGO_TEST_ROOT".to_owned(), root.to_str().unwrap().to_owned())],
        manifest_path: None,
        config: &[],
        features: &[],
        all_features: false,
        no_default_features: false,
        build: Some(Build { packages: &[], workspace: false, excludes: &[], dev_units: false }),
        platform: Some(TargetPlatform { triple: "x86_64-unknown-linux-gnu", cfg: &[] }),
        offline,
        store: None,
    };
    unit_graph_captured(
        &UnitsAsked {
            asked: &asked,
            command: Command::Build,
            targets: &TargetFilter::default(),
            profile: None,
        },
        captured,
        None,
    )
}

fn git(root: &Path, args: &[&str]) -> String {
    let output = std::process::Command::new("git").current_dir(root).args(args).output().unwrap();
    assert!(output.status.success(), "{}", String::from_utf8_lossy(&output.stderr));
    String::from_utf8(output.stdout).unwrap().trim().to_owned()
}

fn copy_tree(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for entry in std::fs::read_dir(from).unwrap() {
        let entry = entry.unwrap();
        if entry.file_name() == ".git" {
            continue;
        }
        let target = to.join(entry.file_name());
        if entry.file_type().unwrap().is_dir() {
            copy_tree(&entry.path(), &target);
        } else {
            std::fs::copy(entry.path(), target).unwrap();
        }
    }
}

#[test]
fn fetched_git_siblings_replay_without_original_repository_or_cargo_cache() {
    let scratch = Scratch::new("git");
    scratch.write("repo/Cargo.toml", "[workspace]\nmembers=['a','b']\nresolver='2'\n");
    scratch.write(
        "repo/a/Cargo.toml",
        "[package]\nname='a'\nversion='0.1.0'\nedition='2021'\n[dependencies]\nb={path='../b'}\n",
    );
    scratch.write("repo/a/src/lib.rs", "pub fn a()->u8 { b::b() }\n");
    scratch.write("repo/b/Cargo.toml", "[package]\nname='b'\nversion='0.1.0'\nedition='2021'\n");
    scratch.write("repo/b/src/lib.rs", "pub fn b()->u8 { 1 }\n");
    let repo = scratch.0.join("repo");
    git(&repo, &["init", "-q"]);
    git(&repo, &["checkout", "-qb", "fixture"]);
    git(&repo, &["add", "."]);
    git(
        &repo,
        &[
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "-qm",
            "siblings",
        ],
    );
    let revision = git(&repo, &["rev-parse", "HEAD"]);
    let url = url::Url::from_file_path(&repo).unwrap();
    let source = format!("git+{url}?branch=fixture#{revision}");
    scratch.write("app/Cargo.toml", &format!("[package]\nname='app'\nversion='0.1.0'\nedition='2021'\n[dependencies]\na={{git='{url}',branch='fixture'}}\n"));
    scratch.write("app/src/lib.rs", "pub fn value()->u8 { a::a() }\n");
    scratch.write("app/Cargo.lock", &format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\nsource = \"{source}\"\ndependencies = [\n \"b\",\n]\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"a\",\n]\n\n[[package]]\nname = \"b\"\nversion = \"0.1.0\"\nsource = \"{source}\"\n"));
    let root = scratch.0.join("app");
    let home = scratch.0.join("home");
    let (original, _, sources) = graph(&root, &home, false, None).unwrap();
    assert_eq!(sources.len(), 2);
    assert!(sources.iter().all(|entry| entry.source == source));
    let mut replay = sources.clone();
    for entry in &mut replay {
        let destination = scratch.0.join("snapshot").join(&entry.name);
        copy_tree(&entry.root, &destination);
        entry.root = destination;
    }
    std::fs::remove_dir_all(&repo).unwrap();
    std::fs::remove_dir_all(&home).unwrap();
    assert!(
        graph(&root, &home, true, None).is_err(),
        "ordinary Git resolution requires the missing database"
    );
    if home.exists() {
        std::fs::remove_dir_all(&home).unwrap();
    }

    let (reproduced, inputs, retained) = graph(&root, &home, true, Some(&replay)).unwrap();
    assert_eq!(retained, replay);
    assert!(!home.exists(), "captured resolution must not create or inspect a Git cache");
    assert_eq!(reproduced.lock, original.lock);
    assert_eq!(reproduced.roots, original.roots);
    let mut expected = original.units;
    for unit in &mut expected {
        if let Some(before) = sources.iter().find(|entry| entry.name == unit.package.name) {
            let after = replay.iter().find(|entry| entry.name == before.name).unwrap();
            unit.target.src_path =
                after.root.join(unit.target.src_path.strip_prefix(&before.root).unwrap());
            unit.package.manifest_dir.clone_from(&after.root);
        }
    }
    assert_eq!(reproduced.units, expected);
    for source in &replay {
        let manifest = source.root.join("Cargo.toml");
        assert!(
            inputs
                .iter()
                .any(|(path, bytes)| path == &manifest
                    && *bytes == std::fs::read(&manifest).unwrap())
        );
    }
}

fn captured_fixture() -> (Scratch, Vec<CapturedSource>) {
    let scratch = Scratch::new("mappings");
    let revision = "0123456789abcdef0123456789abcdef01234567";
    let git = format!("git+https://example.invalid/dependency?rev={revision}#{revision}");
    let registry = "registry+https://github.com/rust-lang/crates.io-index";
    scratch.write("app/Cargo.toml", &format!("[package]\nname='app'\nversion='0.1.0'\nedition='2021'\n[dependencies]\na={{git='https://example.invalid/dependency',rev='{revision}'}}\nunused={{version='1.0.0',optional=true}}\n"));
    scratch.write("app/src/lib.rs", "pub fn value()->u8 { a::a() }\n");
    scratch.write("app/Cargo.lock", &format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\nsource = \"{git}\"\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"a\",\n \"unused\",\n]\n\n[[package]]\nname = \"unused\"\nversion = \"1.0.0\"\nsource = \"{registry}\"\nchecksum = \"{}\"\n", "ab".repeat(32)));
    scratch
        .write("snapshot/a/Cargo.toml", "[package]\nname='a'\nversion='0.1.0'\nedition='2021'\n");
    scratch.write("snapshot/a/src/lib.rs", "pub fn a()->u8 { 1 }\n");
    scratch.write(
        "snapshot/unused/Cargo.toml",
        "[package]\nname='unused'\nversion='1.0.0'\nedition='2021'\n",
    );
    scratch.write("snapshot/unused/src/lib.rs", "");
    let sources = vec![
        CapturedSource {
            source: git,
            name: "a".into(),
            version: "0.1.0".into(),
            root: scratch.0.join("snapshot/a"),
        },
        CapturedSource {
            source: registry.into(),
            name: "unused".into(),
            version: "1.0.0".into(),
            root: scratch.0.join("snapshot/unused"),
        },
    ];
    (scratch, sources)
}

#[test]
fn captured_registry_and_unselected_locked_packages_need_no_archive_or_index() {
    let (scratch, sources) = captured_fixture();
    let home = scratch.0.join("missing-home");
    let (resolved, _, retained) =
        graph(&scratch.0.join("app"), &home, true, Some(&sources)).unwrap();
    assert_eq!(retained, sources);
    assert!(resolved.units.iter().any(|unit| unit.package.name == "a"));
    assert!(!resolved.units.iter().any(|unit| unit.package.name == "unused"));
    assert!(!home.exists());
    let error = graph(&scratch.0.join("app"), &home, true, Some(&sources[..1])).unwrap_err();
    assert!(format!("{error:#}").contains("missing captured source for unused 1.0.0"));
}

#[test]
fn captured_mappings_require_exact_source_revision_and_package_set() {
    let (scratch, sources) = captured_fixture();
    let check = |mapped: &[CapturedSource], message: &str| {
        let error =
            graph(&scratch.0.join("app"), &scratch.0.join("missing-home"), true, Some(mapped))
                .unwrap_err();
        assert!(format!("{error:#}").contains(message), "{error:#}");
    };
    let mut duplicate = sources.clone();
    duplicate.push(sources[0].clone());
    check(&duplicate, "duplicate captured source");
    let mut wrong_revision = sources.clone();
    wrong_revision[0].source = wrong_revision[0].source.replace(
        "#0123456789abcdef0123456789abcdef01234567",
        "#fedcba9876543210fedcba9876543210fedcba98",
    );
    check(&wrong_revision, "missing captured source for a 0.1.0");
    let mut extra = sources.clone();
    extra.push(CapturedSource { name: "unlocked".into(), ..sources[1].clone() });
    check(&extra, "packages not in Cargo.lock");
    let mut relative = sources.clone();
    relative[0].root = PathBuf::from("relative");
    check(&relative, "source root is not absolute");
    check(&[], "missing captured source");
}

#[test]
fn captured_manifest_must_contain_its_claimed_locked_package() {
    let (scratch, sources) = captured_fixture();
    scratch.write(
        "snapshot/a/Cargo.toml",
        "[package]\nname='different'\nversion='0.1.0'\nedition='2021'\n",
    );
    let error =
        graph(&scratch.0.join("app"), &scratch.0.join("missing-home"), true, Some(&sources))
            .unwrap_err();
    assert!(format!("{error:#}").contains("expected locked package a 0.1.0"));
}
